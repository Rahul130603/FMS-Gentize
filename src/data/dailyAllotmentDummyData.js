/**
 * Formats YYYY-MM-DD date into "05 Sep 2026"
 */
export const formatDisplayDate = (dateStr) => {
  if (!dateStr) return '';
  try {
    const parts = dateStr.split('-');
    if (parts.length !== 3) return dateStr;
    const [year, month, day] = parts;
    const months = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];
    const monthName = months[parseInt(month, 10) - 1] || month;
    return `${day} ${monthName} ${year}`;
  } catch {
    return dateStr;
  }
};

/**
 * Returns deterministic past report employee records for any selected date
 */
export const getEmployeeRecordsForDate = (dateStr) => {
  if (!dateStr || dateStr === CURRENT_REPORT_DATE) {
    return INITIAL_EMPLOYEE_RECORDS;
  }

  // Generate deterministic past records for the specified date
  const seed = dateStr.split('-').reduce((acc, part) => acc + parseInt(part, 10), 0);
  
  return INITIAL_EMPLOYEE_RECORDS.map((emp) => {
    const variance = ((emp.id * 7 + seed) % 7) - 3;
    const allocated = Math.max(12, emp.allocated + variance);
    const target = emp.dailyTarget || allocated;
    
    // Past dates have ended, so completion rate is typically high (75% - 100%)
    const completionPercent = 75 + ((emp.id * 11 + seed) % 25);
    const completed = Math.min(allocated, Math.round((allocated * completionPercent) / 100));
    
    const rework = (emp.id + seed) % 6 === 0 ? 1 : ((emp.id + seed) % 13 === 0 ? 2 : 0);
    const remainingAfterCompleted = allocated - completed;
    const wip = (emp.id + seed) % 5 === 0 ? Math.min(2, remainingAfterCompleted) : 0;
    const pending = Math.max(0, remainingAfterCompleted - wip);

    let status = "Completed";
    if (rework > 1) status = "Rework";
    else if (wip > 0) status = "WIP";
    else if (pending > 3) status = "Pending";
    else status = "Completed";

    return {
      ...emp,
      date: dateStr,
      allocated,
      dailyTarget: target,
      completed,
      wip,
      pending,
      rework,
      status,
      downloaded: allocated,
      firstDownload: "09:05 AM",
      lastUpload: "05:45 PM",
      files: generateDetailedFiles(
        470000 + (seed * 100) + emp.id, 
        allocated, 
        completed, 
        wip, 
        rework, 
        pending, 
        emp.project || "Production", 
        "Normal"
      )
    };
  });
};


